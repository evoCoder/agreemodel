/** HTML термина с подсказкой. */
export function term(word, shown = word) {
  const tip = TERMS[word] || TERMS[word.toLowerCase()];
  if (!tip) return shown;
  return `<span class="term" tabindex="0" data-tip="${tip.replace(/"/g, "&quot;")}">${shown}</span>`;
}

/** Расставить подсказки элементам с data-term="…". */
export function applyTerms(root = document) {
  for (const el of root.querySelectorAll("[data-term]")) {
    const tip = TERMS[el.dataset.term];
    if (tip) { el.classList.add("term"); el.dataset.tip = tip; el.tabIndex = 0; }
  }
  for (const el of root.querySelectorAll("[data-hint]")) {
    const tip = FIELD_HINTS[el.dataset.hint];
    if (tip && !el.querySelector(".hint-i")) {
      const i = document.createElement("span");
      i.className = "hint-i"; i.tabIndex = 0; i.textContent = "?"; i.dataset.tip = tip;
      el.prepend(i);
    }
  }
}
